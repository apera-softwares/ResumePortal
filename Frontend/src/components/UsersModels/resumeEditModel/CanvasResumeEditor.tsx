// Helper to preserve PDF layout while normalizing nowrap text properties
export function cleanInlineStyleString(styleStr: string | null): string | null {
  if (!styleStr) return null;
  let cleaned = styleStr
    .replace(/position\s*:\s*absolute;?/gi, "position: relative;")
    .replace(/\btop\s*:\s*[^;"]+;?/gi, "")
    .replace(/\bleft\s*:\s*[^;"]+;?/gi, "")
    .replace(/white-space\s*:\s*nowrap;?/gi, "white-space: pre-wrap;");
  return cleaned.trim() || null;
}

// Helper to prepare parsed PDF HTML for smooth visual editing without empty pages, outline links, or huge vertical gaps
export function sanitizeResumeHtmlForEditor(html: string): string {
  if (!html) return "";
  let sanitized = html;

  // 1. Strip pdftohtml "Document Outline" section and bookmark links completely
  sanitized = sanitized.replace(/<hr\s*\/?>\s*<a\s+name="outline">[\s\S]*$/gi, "");
  sanitized = sanitized.replace(/<a\s+name="outline">[\s\S]*$/gi, "");
  sanitized = sanitized.replace(/<h1>Document Outline<\/h1>[\s\S]*$/gi, "");
  sanitized = sanitized.replace(/<a\s+href="#\d+"[^>]*>[\s\S]*?<\/a>/gi, "");

  // 2. Remove empty page divs generated by pdftohtml that create blank stacked pages
  sanitized = sanitized.replace(
    /<div\s+id="page\d+-div"[^>]*>([\s\S]*?)<\/div>/gi,
    (match, innerContent) => {
      const textOnly = innerContent.replace(/<[^>]*>/g, "").replace(/\s+/g, "").trim();
      if (!textOnly && !innerContent.includes("<img")) {
        return "";
      }
      return match;
    }
  );

  // 3. Clean <style> blocks to allow pre-wrap
  sanitized = sanitized.replace(/<style\b[^>]*>([\s\S]*?)<\/style>/gi, (match, styleContent) => {
    const cleanedStyle = styleContent.replace(/white-space\s*:\s*nowrap/gi, "white-space: pre-wrap");
    return `<style>${cleanedStyle}</style>`;
  });

  // 4. Normalize white-space: nowrap in inline styles to pre-wrap
  sanitized = sanitized.replace(/white-space\s*:\s*nowrap/gi, "white-space: pre-wrap");

  return sanitized;
}

// Custom Node and Mark definitions to preserve all PDF layout styles & IDs
const CustomParagraph = Paragraph.extend({
  addAttributes() {
    return {
      style: {
        default: null,
        parseHTML: element => cleanInlineStyleString(element.getAttribute("style")),
        renderHTML: attributes => attributes.style ? { style: cleanInlineStyleString(attributes.style) } : {},
      },
      id: {
        default: null,
        parseHTML: element => element.getAttribute("id"),
        renderHTML: attributes => attributes.id ? { id: attributes.id } : {},
      },
      class: {
        default: null,
        parseHTML: element => element.getAttribute("class"),
        renderHTML: attributes => attributes.class ? { class: attributes.class } : {},
      }
    };
  },
  addKeyboardShortcuts() {
    return {
      Enter: () => {
        // If inside list item, perform list item split
        if (this.editor.isActive("bulletList") || this.editor.isActive("orderedList")) {
          return this.editor.commands.splitBlock();
        }
        // Seamless line break: move cursor directly to next line below without splitting block containers
        return this.editor.commands.setHardBreak();
      },
    };
  },
});

