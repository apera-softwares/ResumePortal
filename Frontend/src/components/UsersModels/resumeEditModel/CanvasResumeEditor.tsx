// JSON fallback parser to support older data schema, if any
export function jsonToHtml(jsonStr: string): string {
  try {
    const data = JSON.parse(jsonStr);
    if (typeof data === "string") return data;
    return jsonStr;
  } catch (e) {
    return jsonStr;
  }
}

